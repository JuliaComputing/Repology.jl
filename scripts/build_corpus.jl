# Build test/corpus.toml: known-good URL/commit => (project, version) identifications harvested from GeneralMetadata.jl
#
#   julia --project=scripts scripts/build_corpus.jl /path/to/GeneralMetadata.jl
#
# Two kinds of entries are collected:
#   * "manual": upstream info that a human added or changed in GeneralMetadata's git history
#   * "jll-version": automatically identified upstream versions that exactly match the JLL's own version
using TOML: TOML

const UPSTREAM_PREFIX = "repology.org/project/"
const FIELD_ORDER = ["jll", "jll_version", "kind", "url", "hash", "project", "version"]

aslist(x) = x isa AbstractDict ? [x] : x isa AbstractVector ? filter(y->y isa AbstractDict, x) : []

function upstream_sources(meta)
    result = Dict{Tuple{String,String},Dict{String,Any}}()
    for (jllver, verinfo) in meta
        verinfo isa AbstractDict || continue
        for artifactmeta in aslist(get(verinfo, "artifact_metadata", []))
            for source in aslist(get(artifactmeta, "sources", []))
                haskey(source, "url") && haskey(source, "upstream") || continue
                up = source["upstream"]
                startswith(get(up, "project", ""), UPSTREAM_PREFIX) || continue
                key = (source["url"], get(source, "type", "") == "git" ? get(source, "hash", "") : "")
                result[key] = Dict{String,Any}(
                    "jll_version" => jllver,
                    "project" => chopprefix(up["project"], UPSTREAM_PREFIX),
                    "version" => get(up, "version", ""))
            end
        end
    end
    return result
end

function parse_at(gm, rev, path)
    io = IOBuffer()
    success(pipeline(`git -C $gm show $rev:$path`, stdout=io, stderr=devnull)) || return Dict{String,Any}()
    parsed = TOML.tryparse(String(take!(io)))
    return parsed isa TOML.ParserError ? Dict{String,Any}() : parsed
end

function manual_keys(gm)
    keys = Set{Tuple{String,String,String}}() # (path, url, hash)
    commits = split(readchomp(`git -C $gm log --no-merges --perl-regexp '--author=^(?!github-actions)' --format=%H -- metadata`))
    for c in commits
        for path in split(readchomp(`git -C $gm diff-tree --no-commit-id --name-only -r $c -- metadata`))
            before = upstream_sources(parse_at(gm, "$c^", path))
            after = upstream_sources(parse_at(gm, c, path))
            for (k, v) in after
                old = get(before, k, nothing)
                if isnothing(old) || old["project"] != v["project"] || old["version"] != v["version"]
                    push!(keys, (path, k...))
                end
            end
        end
    end
    return keys
end

function main(gm)
    entries = Dict{Tuple{String,String},Dict{String,Any}}()
    for (path, url, hash) in manual_keys(gm)
        current = upstream_sources(TOML.parsefile(joinpath(gm, path)))
        haskey(current, (url, hash)) || continue
        entries[(url, hash)] = merge(current[(url, hash)], Dict("kind" => "manual", "jll" => chopsuffix(basename(path), ".toml")))
    end
    for (root, _, files) in walkdir(joinpath(gm, "metadata")), file in files
        endswith(file, "_jll.toml") || continue
        for (k, v) in upstream_sources(TOML.parsefile(joinpath(root, file)))
            haskey(entries, k) && continue
            v["version"] == first(split(v["jll_version"], '+')) || continue
            entries[k] = merge(v, Dict("kind" => "jll-version", "jll" => chopsuffix(file, ".toml")))
        end
    end
    out = [merge(Dict{String,Any}("url" => url), isempty(hash) ? Dict{String,Any}() : Dict{String,Any}("hash" => hash), v)
           for ((url, hash), v) in entries]
    sort!(out, by=x->(x["jll"], x["url"], get(x, "hash", "")))
    open(joinpath(@__DIR__, "..", "test", "corpus.toml"), "w") do io
        println(io, "# Autogenerated by scripts/build_corpus.jl from GeneralMetadata.jl; known-good identifications")
        TOML.print(io, Dict("entry" => out); sorted=true, by=k->(something(findfirst(==(k), FIELD_ORDER), 99), k))
    end
    @info "wrote $(length(out)) entries" manual=count(x->x["kind"]=="manual", out)
end

if abspath(PROGRAM_FILE) == @__FILE__
    main(ARGS[1])
end
